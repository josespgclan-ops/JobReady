-- Ampliacion no destructiva del modelo JobReady para PostgreSQL.
-- Agrega preguntas y respuestas sin modificar las tablas existentes.

CREATE TABLE IF NOT EXISTS preguntas_entrevista (
    id_pregunta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrera INTEGER NULL,
    texto_pregunta TEXT NOT NULL,
    categoria VARCHAR(50),
    nivel_dificultad VARCHAR(20),
    activo BOOLEAN DEFAULT TRUE,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_preguntas_carreras
        FOREIGN KEY (id_carrera) REFERENCES carreras(id_carrera)
);

CREATE TABLE IF NOT EXISTS respuestas_entrevista (
    id_respuesta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_simulacion INTEGER NOT NULL,
    id_pregunta INTEGER NOT NULL,
    id_archivo INTEGER NULL,
    texto_respuesta TEXT,
    duracion_segundos INTEGER,
    fecha_respuesta TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) DEFAULT 'enviada',
    CONSTRAINT uk_respuesta_simulacion_pregunta
        UNIQUE (id_simulacion, id_pregunta),
    CONSTRAINT fk_respuestas_simulaciones
        FOREIGN KEY (id_simulacion) REFERENCES simulaciones(id_simulacion) ON DELETE CASCADE,
    CONSTRAINT fk_respuestas_preguntas
        FOREIGN KEY (id_pregunta) REFERENCES preguntas_entrevista(id_pregunta),
    CONSTRAINT fk_respuestas_archivos
        FOREIGN KEY (id_archivo) REFERENCES archivos_simulacion(id_archivo) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_preguntas_carrera
    ON preguntas_entrevista(id_carrera);

CREATE INDEX IF NOT EXISTS idx_respuestas_simulacion
    ON respuestas_entrevista(id_simulacion);

CREATE INDEX IF NOT EXISTS idx_respuestas_pregunta
    ON respuestas_entrevista(id_pregunta);
